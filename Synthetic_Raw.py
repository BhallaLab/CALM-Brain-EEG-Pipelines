def discover_vhdr(cfg) -> list[Path]:
    dataset = Dataset.get(name=cfg["dataset_name"])
    layout = dataset.components[0]
    files = layout.query(datatype="eeg", task="rest", extension=".vhdr") # querying with almirah

    wanted = {(f"sub-{s}", f"ses-{e}") for s, e in cfg["subject_sessions"]}
    found = {}
    for f in files:
        p = Path(f.path)
        sub = p.parents[2].name 
        ses = p.parents[1].name  
        key = (sub, ses)
        if key in wanted and key not in found:
            found[key] = p

    paths = [found[k] for k in sorted(found.keys())]
    return paths


def load_raw(vhdr: Path) -> mne.io.Raw:
    return mne.io.read_raw_brainvision(str(vhdr), preload=True, verbose=False)


def find_stim_onsets(raw: mne.io.Raw, cfg) -> tuple[float, str, float, str]:
    ignore_prefixes = ("New Segment", "BAD", "EDGE") # annotations ignored, only stimulus markers considered
    anns = sorted(
        (
            (onset, desc)
            for onset, desc in zip(raw.annotations.onset, raw.annotations.description)
            if not desc.startswith(ignore_prefixes)
        ),
        key=lambda x: x[0],
    )
    if not anns:
        raise ValueError("No stimulus markers found in this recording.") # available stimulus markers vary between files

    lo, hi = cfg["stim1_search_window_s"]
    first_candidate = next((a for a in anns if lo <= a[0] <= hi), None)
    if first_candidate is None:
        raise ValueError(f"No stimulus marker found in the {lo}-{hi}s window.")
    label1 = first_candidate[1]
    onset1 = min(o for o, d in anns if d == label1)  # earliest click, ignore repeats

    later = [(o, d) for o, d in anns if d != label1 and o > onset1]
    if not later:
        raise ValueError("No second, distinct stimulus marker found after the first.")
    label2 = later[0][1]
    onset2 = min(o for o, d in later if d == label2)  # earliest click, ignore repeats
    return onset1, label1, onset2, label2

def resolve_common_channels(vhdr_paths: list[Path], cfg):
    kept = []
    for p in vhdr_paths:
        raw = mne.io.read_raw_brainvision(str(p), preload=False, verbose=False)
        if raw.info["sfreq"] == cfg["sfreq"]:
            kept.append((p, raw.ch_names)) # retaining only files with the same sfreq

    common = set(kept[0][1])
    for _, names in kept[1:]:
        common &= set(names)

    ref_channels = [ch for ch in kept[0][1] if ch in common]
    return [p for p, _ in kept], ref_channels

def _detrend_segment(arr: np.ndarray) -> np.ndarray:
    if arr.shape[1] >= 2: # an earlier version of this code created files with vertical steps at block seams
        # this code aims to remove those vertical steps by removing the DC offset and linear drift from each channel
        # the linear detrend step removes the mean, so each channel is centred at zero with oscillations 
        # method suggestion from claude
        return detrend(arr, axis=1, type="linear").astype(arr.dtype, copy=False)
    if arr.shape[1] == 1:
        return (arr - arr.mean(axis=1, keepdims=True)).astype(arr.dtype, copy=False)
    return arr

def collate_segments(vhdr_paths: list[Path], ref_channels: list[str], sfreq_ref: float, cfg):
    do_detrend = cfg.get("detrend_segments", True)
    label1_ref, label2_ref = None, None
    baseline_pool, seg1_pool, seg2_pool = [], [], []

    for p in vhdr_paths:
        print(f"  loading {p.name} ...")
        raw = load_raw(p)

        extra = [ch for ch in raw.ch_names if ch not in ref_channels]
        if extra:
            raw.drop_channels(extra) # dropping non-common channels
        raw.reorder_channels(ref_channels)
        lf = cfg.get("line_freq") # the line noise is removed at this stage as the bootstrapping process made
        # it smear across the spectrum, making it impossible to remove later
        if lf:
            harmonics = np.arange(lf, sfreq_ref / 2.0, lf)  # harmonics up to nyquist
            raw.notch_filter(freqs=harmonics, fir_design="firwin", verbose=False)

        onset1, label1, onset2, label2 = find_stim_onsets(raw, cfg)
        if label1_ref is None:
            label1_ref, label2_ref = label1, label2

        data = raw.get_data()  # (n_ch, n_t), Volts
        n_t = data.shape[1]

        s1_start = int(round(onset1 * sfreq_ref)) # grabbed from first stimulus onset time and so on
        s2_start = int(round(onset2 * sfreq_ref))

        baseline = data[:, :s1_start]          # recording start -> stim1 onset
        seg1 = data[:, s1_start:s2_start]       # stim1 onset -> stim2 onset
        seg2 = data[:, s2_start:n_t]            # stim2 onset -> end of recording

        if do_detrend:
            baseline = _detrend_segment(baseline)
            seg1 = _detrend_segment(seg1)
            seg2 = _detrend_segment(seg2)

        baseline_pool.append(baseline)
        seg1_pool.append(seg1)
        seg2_pool.append(seg2)
    return baseline_pool, seg1_pool, seg2_pool, label1_ref, label2_ref


def _equal_gain_ramp(k: int) -> np.ndarray:
    if k <= 0: # no overlap, no ramp
        return np.ones(0) # seams were showing up in the recordings as hard steps, so this section
    # aims to resolve that by creating a raised cosine ramp to smooth the seams
    # the seams are smoothed with a first derivative continuity, so the joins are invisible rather than hard steps
    # method and code suggestion from claude
    t = np.arange(1, k + 1)
    return 0.5 * (1.0 - np.cos(np.pi * t / (k + 1)))


def synthesize_segment(pool: list[np.ndarray], seg_len: int, sfreq: float,
                       rng: np.random.Generator, cfg) -> np.ndarray:
    n_ch = pool[0].shape[0] # pooling segments from all subjects, so number of channels is same across all subjects
    block_target = max(1, int(round(cfg["dynamics_block_duration_s"] * sfreq)))
    fade_len = max(0, int(round(block_target * cfg["block_crossfade_frac"])))
    # jitter added to each block's length for variations in seam placement
    jitter = float(cfg.get("block_jitter_frac", 0.4))
    lo_blk = max(1, int(round((1.0 - jitter) * block_target)))
    hi_blk = max(lo_blk, int(round((1.0 + jitter) * block_target)))
    dtype = pool[0].dtype # code assistance from claude

    donors = [s for s in pool if s.shape[1] > 0]

    # headroom = the largest a single block can be, so a long final block
    # always fits before truncation (jitter lets take exceed block_target)
    buf = np.zeros((n_ch, seg_len + hi_blk), dtype=dtype)
    filled = 0
    guard, max_iters = 0, 10 * (seg_len // max(1, lo_blk) + 2)

    while filled < seg_len:
        guard += 1
        if guard > max_iters:
            raise RuntimeError("Block bootstrap failed to converge; check segment lengths.")

        subj = donors[rng.integers(0, len(donors))]
        sub_len = subj.shape[1]
        want = int(rng.integers(lo_blk, hi_blk + 1))   # jittered target length
        take = int(min(want, sub_len))
        start = int(rng.integers(0, sub_len - take + 1)) if sub_len > take else 0
        block = subj[:, start:start + take].copy()   # (n_ch, take) -- all channels, one snippet

        if filled == 0:
            buf[:, :take] = block
            filled = take
            continue

        # overlap the new head onto the previous tail, then blend
        k = min(fade_len, filled, take - 1)
        if k <= 0:
            buf[:, filled:filled + take] = block
            filled += take
            continue

        # shift the incoming block (per channel) so its overlap
        # region sits at the same level as the outgoing tail
        seam0 = filled - k
        offset = buf[:, seam0:filled].mean(axis=1) - block[:, :k].mean(axis=1)
        block += offset[:, None]

        w = _equal_gain_ramp(k)                       # broadcasts over channels
        buf[:, seam0:filled] = buf[:, seam0:filled] * (1.0 - w) + block[:, :k] * w
        buf[:, filled:filled + (take - k)] = block[:, k:]
        filled += take - k

    out = buf[:, :seg_len]
    return _detrend_segment(out)


def write_brainvision(out_stem: Path, data: np.ndarray, sfreq: float,
                       ch_names: list[str], stim_markers: list[tuple[int, str]]): # write brainvision triplet - vhdr, eeg, vmrk
    vhdr = out_stem.with_suffix(".vhdr")
    vmrk = out_stem.with_suffix(".vmrk")
    eeg  = out_stem.with_suffix(".eeg")

    n_ch, n_t = data.shape
    data_uv = (data * 1e6).astype(np.float32)   # saves in uV as per convention, but MNE uses Volts internally

    with open(eeg, "wb") as f:
        f.write(data_uv.T.astype("<f4").tobytes())

    vmrk_lines = [
        "BrainVision Data Exchange Marker File, Version 1.0",
        "",
        "[Common Infos]",
        "Codepage=UTF-8",
        f"DataFile={eeg.name}",
        "",
        "[Marker Infos]",
        "Mk1=New Segment,,1,1,0",
    ]
    for i, (samp, desc) in enumerate(stim_markers, start=2):
        vmrk_lines.append(f"Mk{i}=Stimulus,{desc},{samp + 1},1,0")
    vmrk_lines.append("")
    vmrk.write_text("\r\n".join(vmrk_lines), encoding="utf-8")

    # vhdr
    res_uv = 1.0   # 1 uV resolution 
    hdr_lines = [
        "BrainVision Data Exchange Header File Version 1.0",
        "",
        "[Common Infos]",
        "Codepage=UTF-8",
        f"DataFile={eeg.name}",
        f"MarkerFile={vmrk.name}",
        "DataFormat=BINARY",
        "DataOrientation=MULTIPLEXED",
        f"NumberOfChannels={n_ch}",
        f"DataPoints={n_t}",
        f"SamplingInterval={int(round(1e6 / sfreq))}",   # microseconds
        "",
        "[Binary Infos]",
        "BinaryFormat=IEEE_FLOAT_32",
        "",
        "[Channel Infos]",
    ]
    for i, name in enumerate(ch_names, 1):
        hdr_lines.append(f"Ch{i}={name},,{res_uv:.6f},\u00b5V")
    hdr_lines.append("")
    vhdr.write_text("\r\n".join(hdr_lines), encoding="utf-8")


def run(cfg):
    out_dir = Path(cfg["out_dir"])
    out_dir.mkdir(parents=True, exist_ok=True)

    vhdr_paths = discover_vhdr(cfg)
    vhdr_paths, ch_names, sfreq = resolve_common_channels(vhdr_paths, cfg)
    baseline_pool, seg1_pool, seg2_pool, label1, label2 = collate_segments(
        vhdr_paths, ch_names, sfreq, cfg
    )

    master = np.random.default_rng(cfg["seed"])
    n_synth = cfg["n_subjects"]

    for k in range(1, n_synth + 1):
        sub = cfg["subject_fmt"].format(k)
        rng = np.random.default_rng(master.integers(0, 2**32 - 1))
        # timing profile for each synthetic subject is taken from a random real subject
        n_real = len(baseline_pool)
        donor_idx = rng.integers(0, n_real)
        baseline_len = baseline_pool[donor_idx].shape[1]
        seg1_len = seg1_pool[donor_idx].shape[1]
        seg2_len = seg2_pool[donor_idx].shape[1]

        synth_baseline = synthesize_segment(baseline_pool, baseline_len, sfreq, rng, cfg)
        synth_seg1 = synthesize_segment(seg1_pool, seg1_len, sfreq, rng, cfg)
        synth_seg2 = synthesize_segment(seg2_pool, seg2_len, sfreq, rng, cfg)
        synth_data = np.concatenate([synth_baseline, synth_seg1, synth_seg2], axis=1)

        stim_markers = [(baseline_len, label1), (baseline_len + seg1_len, label2)]

        out_stem = out_dir / f"{sub}_task-rest_eeg"
        write_brainvision(out_stem, synth_data, sfreq, ch_names, stim_markers)

