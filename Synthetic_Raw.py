'''
automated pipeline for the generation of synthetic eeg data from real resting state data from calm-brain. the synthetic data is
generated by block bootstrapping segments of around 1.5 seconds from real subjects and then stitching them together at a max length 
of around 600 seconds. the goal of this data is to provide a means to test pipelines without touching the real data, and thus channel 
correlations and epoch features are preserved. all outputs are saved as per the brainvision triplet format (.vhdr, .eeg, .vmrk) 
and can be read in with mne.io.read_raw_brainvision. 

in the real recordings, each recording has two distict stimulus types: eyes open and eyes closed. the operator seems to have clicked 
the trigger button several times for the same stimulus, so duplicates are ignored by choosing the first onset of each stimulus type.
stim 1 = first thirty seconds, stim 2 = around 300 seconds or midpoint of recording.
these recordings are divided into baseline (0 to stim 1 onset), and then two segments (stim 1 - stim 2; stim 2 - end). each synthetic
file borrows a random real subject's length and stim onset distribution. 

some parameters have been hardcoded in to accommodate issues when bootstrapping segments from different real subjects including large
vertical lines at seams and signal dropoff or misalignment. this also helps preseve short timescale oscillations and trends. these
blocks are all taken from all channels within one subject to preserve channel relationships, which a crucial aspect to preserve if 
ICA has to be applied to this data. Channel order is also fixed amonsgt all subjects. 

pooling works by creating a list of arrays (n_channels, len_i) per real subject. block of the required length are drawn from these subject
at a random start position, and the same donor and offset time are used from every channel within a block. from this, a brainvision 
triplet is written following all of the conventions of mne and brainvision.

this code was written by vaaruni, with code, method and debugging assitance from claude. 
'''
